def kappa(a, b):
    assert len(a) == len(b)
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum((ca[k] / n) * (cb[k] / n) for k in set(ca) | set(cb))
    return (po - pe) / (1 - pe) if pe < 1 else 1.0


def main():
    import sys
    confirm = len(sys.argv) > 1 and sys.argv[1] == "confirm"
    csv_name = "f4_confirm.csv" if confirm else "f4_sample.csv"
    labels = B2 if confirm else B
    rows = list(csv.DictReader((OUT / csv_name).open(encoding="utf-8")))
    B_ = labels
    B = B_  # 保持下游引用一致
    for r in rows:
        b = B[r["id"]]
        for i in range(6):
            r[f"B{i+1}"] = b[i]
        r["B_sev"] = b[6]

    kappas = {}
    disagreements = []
    for i in range(1, 7):
        col_a = [int(r[f"A{i}"]) for r in rows]
        col_b = [int(r[f"B{i}"]) for r in rows]
        kappas[f"C{i}"] = round(kappa(col_a, col_b), 3)
        for r in rows:
            if int(r[f"A{i}"]) != int(r[f"B{i}"]):
                disagreements.append({"id": r["id"], "cat": f"C{i}",
                                      "A": int(r[f"A{i}"]), "B": int(r[f"B{i}"]),
                                      "desc": r["description"][:120]})

    # 严重度加权 kappa（二次加权），只在双方并集阳性条目上计算
    pos = [r for r in rows if any(int(r[f"A{i}"]) or int(r[f"B{i}"]) for i in range(1, 7))]
    sev_a = [int(r["A_sev"]) for r in pos]
    sev_b = [int(r["B_sev"]) for r in pos]
    wk = None
    if pos:
        n = len(pos)
        num = den = 0.0
        for i in range(n):
            for j in range(n):
                w = (sev_a[i] - sev_b[j]) ** 2 / 9.0
                num += w
        # 简化：用线性加权 kappa 等价式较繁琐，这里报告 exact agreement 与 ±1 内一致率
        exact = sum(a == b for a, b in zip(sev_a, sev_b)) / n
        within1 = sum(abs(a - b) <= 1 for a, b in zip(sev_a, sev_b)) / n
        wk = {"n_positive_union": n, "sev_exact": round(exact, 3), "sev_within1": round(within1, 3)}

    report = {
        "n": len(rows),
        "kappa_per_category": kappas,
        "kappa_macro": round(sum(kappas.values()) / 6, 3),
        "positive_union": len(pos),
        "severity_agreement": wk,
        "n_disagreements": len(disagreements),
        "disagreements": disagreements,
    }
    (OUT / "f4_kappa.json").write_text(json.dumps(report, ensure_ascii=False, indent=2),
                                       encoding="utf-8")

    # 回写合并版 CSV
    with (OUT / "f4_sample_annotated.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    print(json.dumps({k: v for k, v in report.items() if k != "disagreements"},
                     ensure_ascii=False, indent=2))
    print("\n分歧明细：")
    for d in disagreements:
        print(f"  {d['id']} {d['cat']} A={d['A']} B={d['B']}  {d['desc']}")
    return 0


if __name__ == "__main__":
    main()
